// Generates the Material 3 colour roles (--md-sys-color-*) for the light and the dark scheme from one seed
// colour, plus the Tailwind bridge (--color-*). Pure function, no Node APIs: the package ships it as
// `@onelitefeathernet/pavo/tokens`, and `pnpm tokens` writes the default output to src/runtime/css/tokens.css.
//
// Vibrant keeps the seed chroma, so the primary stays recognisably OLF blue while the surfaces stay calm.
// The on-* roles reach WCAG AA by construction. Success and warning are not part of M3: they are tonal
// palettes of the OLF green and yellow with the same tone mapping the standard roles use.
import {
  argbFromHex,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeVibrant,
  TonalPalette,
} from '@material/material-color-utilities'

export const DEFAULT_SEED = '#114cc8'

const SUCCESS_SEED = '#1bc755'
const WARNING_SEED = '#f7cc2e'

export interface BuildTokensOptions {
  /** Seed colour as #rrggbb. Defaults to the OLF blue. */
  seed?: string
}

// The roles of MaterialDynamicColors that are colours (the rest are helpers or palette key colours).
const ROLES = Object.getOwnPropertyNames(MaterialDynamicColors).filter((name) => {
  if (/KeyColor$|^highestSurface$|^contentAccentToneDelta$/.test(name)) return false
  const role = (MaterialDynamicColors as unknown as Record<string, { getArgb?: unknown } | undefined>)[name]
  return typeof role?.getArgb === 'function'
})

// Tones for [colour, on-colour, container, on-container].
const EXTRA_TONES = { light: [40, 100, 90, 10], dark: [80, 20, 30, 90] } as const

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)
}

function scheme(seed: string, dark: boolean): Record<string, string> {
  const s = new SchemeVibrant(Hct.fromInt(argbFromHex(seed)), dark, 0)
  const out: Record<string, string> = {}
  for (const role of ROLES) {
    const color = (MaterialDynamicColors as unknown as Record<string, { getArgb: (s: SchemeVibrant) => number }>)[role]!
    out[kebab(role)] = hexFromArgb(color.getArgb(s))
  }
  const tones = dark ? EXTRA_TONES.dark : EXTRA_TONES.light
  for (const [name, hex] of [['success', SUCCESS_SEED], ['warning', WARNING_SEED]] as const) {
    const palette = TonalPalette.fromInt(argbFromHex(hex))
    const [color, on, container, onContainer] = tones.map(t => hexFromArgb(palette.tone(t)))
    out[name] = color!
    out[`on-${name}`] = on!
    out[`${name}-container`] = container!
    out[`on-${name}-container`] = onContainer!
  }
  return out
}

function block(selector: string, vars: Record<string, string>, colorScheme: 'light' | 'dark', indent = ''): string {
  const declarations = Object.entries(vars).map(([k, v]) => `${indent}  --md-sys-color-${k}: ${v};`).join('\n')
  return `${indent}${selector} {\n${indent}  color-scheme: ${colorScheme};\n${declarations}\n${indent}}\n`
}

/** The complete tokens stylesheet for a seed colour. `pnpm tokens` writes it to src/runtime/css/tokens.css. */
export function buildTokensCss(options: BuildTokensOptions = {}): string {
  const seed = options.seed ?? DEFAULT_SEED
  const light = scheme(seed, false)
  const dark = scheme(seed, true)
  return `/* Generated by Pavo from seed ${seed} (Vibrant). Do not edit; run \`pnpm tokens\`. */\n\n`
    + block(':root', light, 'light')
    + '\n/* Dark scheme: the system preference, unless the user picked a theme explicitly. */\n'
    + `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, 'dark', '  ')}}\n\n`
    + block(':root[data-theme="dark"]', dark, 'dark')
    + '\n/* Tailwind utilities: bg-primary, text-on-surface, border-outline-variant, ... */\n'
    + `@theme inline {\n${Object.keys(light).map(k => `  --color-${k}: var(--md-sys-color-${k});`).join('\n')}\n}\n`
}
